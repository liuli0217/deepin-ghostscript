#define SASLPREP_B3_TABLE_LEN (sizeof(saslprep_b3_table) / sizeof(saslprep_b3_table[0]))

/* ---- Helper functions ---- */

static int
in_range_table(ucs4_t uc, const saslprep_range *table, int len)
{
    int lo = 0, hi = len - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (uc < table[mid].start)
            hi = mid - 1;
        else if (uc > table[mid].end)
            lo = mid + 1;
        else
            return 1;
    }
    return 0;
}

static const saslprep_b3_entry *
find_b3(ucs4_t uc)
{
    int lo = 0, hi = (int)SASLPREP_B3_TABLE_LEN - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (uc < saslprep_b3_table[mid].cp)
            hi = mid - 1;
        else if (uc > saslprep_b3_table[mid].cp)
            lo = mid + 1;
        else
            return &saslprep_b3_table[mid];
    }
    return NULL;
}

/* ---- Prohibit check (RFC 3454 Section C) ---- */

static int
is_prohibited(ucs4_t uc)
{
    /* C.1.2: non-ASCII space separators (Zs, not U+0020) */
    if (uc != 0x0020 && uc_is_general_category(uc, UC_CATEGORY_Zs))
        return 1;

    /* C.2.1: ASCII control characters (Cc, < 0x80) */
    if (uc < 0x80 && uc_is_general_category(uc, UC_CATEGORY_Cc))
        return 1;

    /* C.2.2: non-ASCII control characters */
    if (uc >= 0x80) {
        if (uc_is_general_category(uc, UC_CATEGORY_Cc))
            return 1;
        if (in_range_table(uc, saslprep_c22_specials, SASLPREP_C22_SPECIALS_LEN))
            return 1;
    }

    /* C.3: private use (Co) */
    if (uc_is_general_category(uc, UC_CATEGORY_Co))
        return 1;

    /* C.4: non-character codepoints */
    if ((uc >= 0xFDD0 && uc <= 0xFDEF) ||
        ((uc & 0xFFFE) == 0xFFFE))
        return 1;

    /* C.5: surrogates (Cs) */
    if (uc_is_general_category(uc, UC_CATEGORY_Cs))
        return 1;

    /* C.6 */
    if (in_range_table(uc, saslprep_c6, SASLPREP_C6_LEN))
        return 1;

    /* C.7 */
    if (in_range_table(uc, saslprep_c7, SASLPREP_C7_LEN))
        return 1;

    /* C.8 */
    if (in_range_table(uc, saslprep_c8, SASLPREP_C8_LEN))
        return 1;

    /* C.9 */
    if (in_range_table(uc, saslprep_c9, SASLPREP_C9_LEN))
        return 1;

    return 0;
}

/* ---- Bidi check (RFC 3454 Section D) ---- */

static int
bidi_check(const ucs4_t *ucs, int n)
{
    int has_randal = 0;
    int has_lcat = 0;
    int i;

    for (i = 0; i < n; i++) {
        int bc = uc_bidi_class(ucs[i]);
        if (bc == UC_BIDI_R || bc == UC_BIDI_AL)
            has_randal = 1;
        else if (bc == UC_BIDI_L)
            has_lcat = 1;
    }

    if (!has_randal)
        return 1; /* no RandALCat characters — OK */

    if (has_lcat)
        return 0; /* RandALCat + LCat — violation */

    /* First and last characters must be RandALCat */
    {
        int bc_first = uc_bidi_class(ucs[0]);
        int bc_last = uc_bidi_class(ucs[n - 1]);
        if (bc_first != UC_BIDI_R && bc_first != UC_BIDI_AL)
            return 0;
        if (bc_last != UC_BIDI_R && bc_last != UC_BIDI_AL)
            return 0;
    }

    return 1;
}

/* ---- SASLprep main function ---- */

int
pdf_saslprep(const char *input, int input_len,
             char **output, int *output_len)
{
    /*
     * Step 1: Mapping (RFC 3454 Section B)
     *   - B.1: map to nothing (skip)
     *   - B.2: case fold (B.3 table exceptions, then uc_tolower)
     */
    /* Worst case: each byte → 1 codepoint → 4 codepoints × 4 bytes = 16x */
    int mapped_buf_size = input_len * 16 + 1;
    uint8_t *mapped = (uint8_t *)malloc(mapped_buf_size);
    int mapped_len = 0;
    const uint8_t *inp = (const uint8_t *)input;
    int pos = 0;
    int i;

    if (mapped == NULL)
        return -1;

    while (pos < input_len) {
        ucs4_t uc;
        int adv = u8_mbtouc(&uc, inp + pos, input_len - pos);
        if (adv <= 0)
            adv = 1; /* skip invalid byte */

        /* B.1: map to nothing */
        if (in_range_table(uc, saslprep_b1, SASLPREP_B1_LEN)) {
            pos += adv;
            continue;
        }

        /* B.2/B.3: case fold */
        {
            const saslprep_b3_entry *entry = find_b3(uc);
            if (entry) {
                for (i = 0; i < entry->map_len; i++) {
                    int w = u8_uctomb(mapped + mapped_len, entry->map[i],
                                      mapped_buf_size - mapped_len);
                    if (w < 0) { free(mapped); return -1; }
                    mapped_len += w;
                }
            } else {
                ucs4_t folded = uc_tolower(uc);
                int w = u8_uctomb(mapped + mapped_len, folded,
                                  mapped_buf_size - mapped_len);
                if (w < 0) { free(mapped); return -1; }
                mapped_len += w;
            }
        }

        pos += adv;
    }

    /*
     * Step 2: NFKC normalization (RFC 3454 Section 2)
     */
    {
        size_t nfkc_len = 0;
        uint8_t *nfkc = u8_normalize(UNINORM_NFKC, mapped, (size_t)mapped_len,
                                      NULL, &nfkc_len);
        free(mapped);
        if (nfkc == NULL)
            return -1; /* hard error: NFKC failed */

        /*
         * Step 3: Prohibit check + Bidi check
         * Convert to UCS4 array for both checks.
         */
        {
            ucs4_t *ucs;
            int n_uc = 0;

            pos = 0;
            /* Count codepoints first */
            while (pos < (int)nfkc_len) {
                ucs4_t dummy;
                int adv = u8_mbtouc(&dummy, nfkc + pos, nfkc_len - pos);
                pos += (adv > 0) ? adv : 1;
                n_uc++;
            }

            ucs = (ucs4_t *)malloc((n_uc + 1) * sizeof(ucs4_t));
            if (ucs == NULL) { free(nfkc); return -1; }

            pos = 0;
            n_uc = 0;
            while (pos < (int)nfkc_len) {
                int adv = u8_mbtouc(&ucs[n_uc], nfkc + pos, nfkc_len - pos);
                pos += (adv > 0) ? adv : 1;
                if (adv > 0)
                    n_uc++;
            }

            /* Prohibit check */
            for (i = 0; i < n_uc; i++) {
                if (is_prohibited(ucs[i])) {
                    free(ucs);
                    free(nfkc);
                    return 1; /* soft error */
                }
            }

            /* Bidi check */
            if (n_uc > 0 && !bidi_check(ucs, n_uc)) {
                free(ucs);
                free(nfkc);
                return 1; /* soft error */
            }

            free(ucs);
        }

        *output = (char *)nfkc;
        *output_len = (int)nfkc_len;
        return 0;
    }
}

